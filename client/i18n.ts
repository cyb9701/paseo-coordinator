/** language 는 서버에 알릴 앱 언어다. 서버는 앱 언어를 모르므로 요약 언어를 정할 때 쓴다. */
export function useT() {
  const translation = useTranslation(messages);
  const language: "en" | "ko" = translation.locale.toLowerCase().startsWith("ko") ? "ko" : "en";
  return { t: translation.t, locale: translation.locale, language };
}

